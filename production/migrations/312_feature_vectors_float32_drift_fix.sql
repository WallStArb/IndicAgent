-- transaction), same reasoning as migration 201: compress_chunk() takes its
-- own per-chunk locks and this way a failure partway through recompression
-- can't roll back the (already-verified) type change.
DO $$
DECLARE
  c record;
BEGIN
  FOR c IN
    SELECT format('%I.%I', chunk_schema, chunk_name)::regclass AS chunk
    FROM timescaledb_information.chunks
    WHERE hypertable_name = 'feature_vectors' AND NOT is_compressed
  LOOP
    PERFORM compress_chunk(c.chunk);
  END LOOP;
END $$;
