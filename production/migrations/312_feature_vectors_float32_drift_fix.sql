-- Migration 312: feature_vectors float64 -> float32 (real) storage type, drift fix
--
-- Migration 201 (2026-07-09) converted 156 double-precision feature columns to
-- real, with the rationale that every consumer already truncates these values
-- to float32 in memory immediately on read (services/ic_engine.py,
-- services/ensemble_trainer.py -- "rank-based IC doesn't need float64 raw
-- values") so storing float64 in the table added zero effective precision.
--
-- Every feature-column-adding migration SINCE 201 reverted to DOUBLE PRECISION
-- instead of following that convention (216 canary predictors, 255 VP/SR
-- structural primitives [Phase 163], 266 SMC institutional footprint [Phase
-- 164], 267 swing/fib/trend structure [Phase 165], 288-293 Phase 151 waves
-- 6-7 primitives, 307 regime-volatility). This migration extends 201's fix to
-- the 303 columns that drifted back to double precision -- same rationale,
-- same audit method (spot-checked column semantics: z-scores, ratios,
-- distances-in-ATR-units, trig encodings, probabilities, small bounded
-- counts, boolean flags -- none carry raw price levels or accumulator sums
-- that would need float8 range/precision).
--
-- Timed deliberately to run as part of the feature_vectors wipe-and-recompute
-- (todo 259 backfill completion -> Phase 151 waves 6-7 + regime rebuild):
-- run this AFTER truncating feature_vectors and BEFORE repopulating, so the
-- decompress/recompress dance below is a no-op on an empty table instead of
-- rewriting 48GB of live compressed data. If run against live data instead,
-- it is still correct -- just slower (mirrors 201's decompress-alter-
-- recompress pattern for that case).

BEGIN;

DO $$
DECLARE
  c record;
BEGIN
  FOR c IN
    SELECT format('%I.%I', chunk_schema, chunk_name)::regclass AS chunk
    FROM timescaledb_information.chunks
    WHERE hypertable_name = 'feature_vectors' AND is_compressed
  LOOP
    PERFORM decompress_chunk(c.chunk);
  END LOOP;
END $$;

